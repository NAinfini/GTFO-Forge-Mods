using System;
using System.Collections.Generic;
using System.Text.Json;
using ForgeEngine.Framework;

namespace ForgeMap;

/// <summary>
/// The authored room a placed object stands in, in the one locator spelling the package's own object references
/// use (`forge-project.forge` `objectReferences`): the author's zone id, that zone's
/// native coordinates, the room definition's identity and the native prefab the room is generated from. The
/// grammar is one grammar, because a room the author can point at in the editor is the same room the runtime
/// resolves, and a second spelling would be a second answer to "which room is this".
///
/// The native coordinates are on the locator because the runtime cannot resolve the author's zone id: the mapping
/// from an authored zone to the zone the level generated lives with the project manifest, and a placed-object
/// document carries no such table. So the document carries the level's own coordinates and the resolver looks
/// inside exactly that zone — never across the whole level, where the same prefab placed in two zones would make
/// every such object unplaceable.
///
/// The locator is data, not a position: where the room really ended up is the level's own answer after generation,
/// and only a resolver that can see the generated level may answer it. The document reader reads the reference;
/// the native half resolves it.
/// </summary>
internal sealed class RoomLocator
{
    /// <summary>A native zone with one occurrence of the source prefab; existing vanilla exports use this kind.</summary>
    public const string Kind = "unique-geomorph-in-zone";
    /// <summary>A room generated by forge/map-generation.forge, identified by its authored instance id.</summary>
    public const string AuthoredKind = "authored-geomorph-in-zone";
    /// <summary>The longest room definition id, matching the package reference grammar.</summary>
    public const int MaximumRoomIdChars = 512;
    /// <summary>The longest native prefab identity, matching the package reference grammar.</summary>
    public const int MaximumPrefabChars = 1024;
    /// <summary>The length of the room definition revision: one SHA-256 in lower-case hex.</summary>
    public const int RevisionChars = 64;
    /// <summary>The greatest layer a zone can stand on, in the site's own zone coordinate grammar.</summary>
    public const int MaximumLayer = 2;

    internal RoomLocator(string zoneAuthorId, int dimension, int layer, int localIndex, string roomId, string revision,
        string sourcePrefab, string? instanceId = null)
    {
        ZoneAuthorId = zoneAuthorId;
        Dimension = dimension;
        Layer = layer;
        LocalIndex = localIndex;
        RoomId = roomId;
        Revision = revision;
        SourcePrefab = sourcePrefab;
        InstanceId = instanceId;
    }

    /// <summary>The authored zone the room belongs to, in the site's own zone identity grammar.</summary>
    public string ZoneAuthorId { get; }
    /// <summary>The native zone's dimension, the coordinate the level's own zone table is addressed by.</summary>
    public int Dimension { get; }
    /// <summary>The native zone's layer inside its dimension, `LG_Zone.m_layer.m_type`.</summary>
    public int Layer { get; }
    /// <summary>The native zone's index inside its layer, `LG_Zone.LocalIndex`.</summary>
    public int LocalIndex { get; }
    /// <summary>The room definition's id inside the package.</summary>
    public string RoomId { get; }
    /// <summary>The room definition's revision, so a room re-authored between export and play is a room the
    /// reference no longer names.</summary>
    public string Revision { get; }
    /// <summary>The native prefab the room is generated from: the identity a resolver matches the generated level
    /// against. A prefab name alone is not this identity, which is why it is carried whole and validated.</summary>
    public string SourcePrefab { get; }
    /// <summary>The MapRoom instance id in forge-project.forge; absent only for a native unique-prefab locator.</summary>
    public string? InstanceId { get; }

    /// <summary>Reads one locator row. Every refusal is one code and one sentence naming the first thing that
    /// could not be read, so a mistyped locator is refused at the document instead of resolving to a room that was
    /// never meant.</summary>
    public static bool TryParse(JsonElement row, out RoomLocator? room, out string? code, out string? reason)
    {
        room = null;
        code = "room-locator";
        reason = null;
        if (row.ValueKind != JsonValueKind.Object) { reason = "A room locator is an object."; return false; }
        if (!DocumentReading.Known(row, out var unknown, "kind", "zoneAuthorId", "dimension", "layer", "localIndex",
                "room", "sourcePrefab", "instanceId"))
        { reason = "Unknown room field `" + unknown + "`."; return false; }
        if (!DocumentReading.Text(row, "kind", 64, out var kind) || (kind != Kind && kind != AuthoredKind))
        { reason = "Unknown room locator kind."; return false; }
        string? instanceId = null;
        if (kind == AuthoredKind)
        {
            if (!DocumentReading.Text(row, "instanceId", 64, out instanceId) || !DocumentReading.AuthorId(instanceId!))
            { reason = "An authored room locator needs its MapRoom instance id."; return false; }
        }
        else if (row.TryGetProperty("instanceId", out _))
        { reason = "A unique-prefab locator cannot carry an authored instance id."; return false; }
        if (!DocumentReading.Text(row, "zoneAuthorId", 64, out var zoneAuthorId) || !DocumentReading.AuthorId(zoneAuthorId!))
        { reason = "A room locator needs the authored zone id it belongs to."; return false; }
        if (!DocumentReading.Coordinate(row, "dimension", 0, int.MaxValue, out var dimension)
            || !DocumentReading.Coordinate(row, "layer", 0, MaximumLayer, out var layer)
            || !DocumentReading.Coordinate(row, "localIndex", 0, int.MaxValue, out var localIndex))
        { reason = "A room locator carries the native zone it stands in as `dimension`, `layer` and `localIndex`."; return false; }
        if (!row.TryGetProperty("room", out var definition) || definition.ValueKind != JsonValueKind.Object)
        { reason = "A room locator carries the room definition it names."; return false; }
        if (!DocumentReading.Known(definition, out unknown, "id", "revision"))
        { reason = "Unknown room definition field `" + unknown + "`."; return false; }
        if (!DocumentReading.Text(definition, "id", MaximumRoomIdChars, out var id) || !DocumentReading.Identity(id!))
        {
            reason = "A room definition id is at most " + MaximumRoomIdChars
            + " characters without whitespace or a path separator."; return false;
        }
        if (!DocumentReading.Text(definition, "revision", RevisionChars, out var revision) || !PublishedResources.IsSha256(revision!))
        { reason = "A room definition revision is one lower-case SHA-256."; return false; }
        if (!DocumentReading.Text(row, "sourcePrefab", MaximumPrefabChars, out var prefab) || !DocumentReading.Prefab(prefab!))
        { reason = "A room locator carries a complete native `Assets/` prefab identity."; return false; }
        room = new RoomLocator(zoneAuthorId!, dimension, layer, localIndex, id!, revision!, prefab!, instanceId);
        return true;
    }

    public override string ToString() => ZoneAuthorId + "/" + (InstanceId == null ? "" : InstanceId + ":") + RoomId + "@" + Revision;
}

/// <summary>
/// Where one room really ended up in the level the game generated: a world position and a unit quaternion in the
/// same `x y z w` order every other pose in this family uses. Only the level's own data can answer this, so the
/// value exists solely to be composed with a placed object's own room-local pose; a pose that is not three finite
/// metres and a unit quaternion is refused by name rather than composed into an object nothing can place.
/// </summary>
internal readonly struct RoomPose
{
    private readonly double[] _position;
    private readonly double[] _rotation;

    private RoomPose(double[] position, double[] rotation)
    {
        _position = position;
        _rotation = rotation;
    }

    /// <summary>The one way to build a pose: the room's world position in metres and its world rotation.</summary>
    public static RoomPose Of(double[] position, double[] rotation)
    {
        ArgumentNullException.ThrowIfNull(position);
        ArgumentNullException.ThrowIfNull(rotation);
        if (position.Length != 3) throw new RuntimeContractException("room-pose", "A room position requires three coordinates.");
        if (rotation.Length != Rotations.Components)
            throw new RuntimeContractException("room-pose", "A room rotation is a unit quaternion in `x y z w` order.");
        foreach (var value in position)
            if (!double.IsFinite(value)) throw new RuntimeContractException("room-pose", "A room position carries finite metre coordinates.");
        foreach (var value in rotation)
            // A unit quaternion's components never exceed one, and one composed rotation can exceed it by the last
            // bit of a double (`2 * sqrt(0.5)²` is `1.0000000000000002`): the tolerance is the same one the unit
            // length test below uses, and the length is what actually decides.
            if (!double.IsFinite(value) || Math.Abs(value) > 1 + Rotations.Tolerance)
                throw new RuntimeContractException("room-pose", "A room rotation is a unit quaternion in `x y z w` order.");
        if (!Rotations.IsUnit(rotation))
            throw new RuntimeContractException("room-pose", "A room rotation is a unit quaternion in `x y z w` order.");
        return new RoomPose((double[])position.Clone(), (double[])rotation.Clone());
    }

    /// <summary>The room's world position.</summary>
    public IReadOnlyList<double> Position => Array.AsReadOnly(_position);
    /// <summary>The room's world rotation, a unit quaternion in `x y z w` order.</summary>
    public IReadOnlyList<double> Rotation => Array.AsReadOnly(_rotation);

    /// <summary>One room-local point in world metres: the room's rotation applied to the offset, then the room's
    /// own position. This is the whole local-to-world half of a placed object's pose.</summary>
    internal double[] Point(IReadOnlyList<double> local)
    {
        var (x, y, z) = Rotations.Rotate(_rotation, local[0], local[1], local[2]);
        return new[] { x + _position[0], y + _position[1], z + _position[2] };
    }

    /// <summary>One room-local rotation in world space: the room's own rotation composed with it.</summary>
    internal double[] Compose(IReadOnlyList<double> local) => Rotations.Multiply(_rotation, local);
}

/// <summary>The one question only the generated level can answer about an authored room: where that room ended up.
/// A document carries a locator instead of a world pose, so a placed object becomes a world object exactly when
/// this answers with the room's world pose.
///
/// The answer is a delegate because the knowledge lives with the level, not with this assembly: the resolver that
/// reads a document's object references against the level the game generated owns the identity rules, and a second
/// lookup written here would be a second answer to which native object an authored room names. Returning null is
/// "this level holds no single room that reference names", which is a refusal and never a guess.</summary>
/// <param name="room">The authored room reference an object carries.</param>
/// <returns>The room's world pose, or null when this resolver cannot name exactly one room for the reference.</returns>
internal delegate RoomPose? RoomLookup(RoomLocator room);

/// <summary>
/// The quaternion arithmetic every pose in this family shares: one rotation applied to a vector, two rotations
/// composed, and the unit test a document's own rotation is accepted at. It is one implementation because a
/// trigger zone, a fixed item and a fixed enemy are placed by the same conversion, and two copies of it would be
/// two answers to where one authored point lands.
/// </summary>
internal static class Rotations
{
    /// <summary>One rotation is four components in the site's `x y z w` order.</summary>
    internal const int Components = 4;
    /// <summary>The tolerance a rotation is accepted as a unit quaternion at.</summary>
    internal const double Tolerance = 0.001;

    /// <summary>One vector rotated by a unit quaternion in `x y z w` order.</summary>
    internal static (double X, double Y, double Z) Rotate(IReadOnlyList<double> rotation, double x, double y, double z)
        => Rotate(rotation[0], rotation[1], rotation[2], rotation[3], x, y, z);

    /// <summary>One vector turned back by a unit quaternion in `x y z w` order: the rotation's conjugate applied, which
    /// takes a world offset into the rotated frame.</summary>
    internal static (double X, double Y, double Z) InverseRotate(IReadOnlyList<double> rotation, double x, double y, double z)
        => Rotate(-rotation[0], -rotation[1], -rotation[2], rotation[3], x, y, z);

    private static (double X, double Y, double Z) Rotate(double qx, double qy, double qz, double qw, double x, double y, double z)
    {
        var tx = 2 * (qy * z - qz * y);
        var ty = 2 * (qz * x - qx * z);
        var tz = 2 * (qx * y - qy * x);
        return (x + qw * tx + qy * tz - qz * ty,
            y + qw * ty + qz * tx - qx * tz,
            z + qw * tz + qx * ty - qy * tx);
    }

    /// <summary>Two rotations composed: the left one applied after the right one, both unit quaternions in
    /// `x y z w` order.</summary>
    internal static double[] Multiply(IReadOnlyList<double> left, IReadOnlyList<double> right)
        => new[]
        {
            left[3] * right[0] + left[0] * right[3] + left[1] * right[2] - left[2] * right[1],
            left[3] * right[1] - left[0] * right[2] + left[1] * right[3] + left[2] * right[0],
            left[3] * right[2] + left[0] * right[1] - left[1] * right[0] + left[2] * right[3],
            left[3] * right[3] - left[0] * right[0] - left[1] * right[1] - left[2] * right[2]
        };

    /// <summary>The one rotation a yaw in degrees is: a rotation about +Y, the authored spelling every placed
    /// object in this family carries.</summary>
    internal static double[] Yaw(double degrees)
    {
        var half = degrees * Math.PI / 360d;
        return new[] { 0d, Math.Sin(half), 0d, Math.Cos(half) };
    }

    /// <summary>The one rotation three Euler degrees are, in Unity's own order (`Quaternion.Euler`: about Z, then X,
    /// then Y), which is the spelling a placed object's authored `Rotation` field carries.</summary>
    internal static double[] Euler(double x, double y, double z)
    {
        static double[] About(int axis, double degrees)
        {
            var half = degrees * Math.PI / 360d;
            var q = new double[] { 0, 0, 0, Math.Cos(half) };
            q[axis] = Math.Sin(half);
            return q;
        }
        return Multiply(About(1, y), Multiply(About(0, x), About(2, z)));
    }

    /// <summary>Whether four components are one unit quaternion within the tolerance every rotation in this family
    /// is accepted at. A rotation that is not one is not a rotation, in a document or in a resolved room pose.</summary>
    internal static bool IsUnit(IReadOnlyList<double> rotation)
    {
        var length = Math.Sqrt(rotation[0] * rotation[0] + rotation[1] * rotation[1]
            + rotation[2] * rotation[2] + rotation[3] * rotation[3]);
        return Math.Abs(length - 1) <= Tolerance;
    }
}
