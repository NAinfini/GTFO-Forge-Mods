using System.Security.Cryptography;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

if (args.Length < 4 || args[0] is not ("inspect" or "write" or "check") || args[2] != "--references" || args.Length % 2 != 0)
{
    Console.Error.WriteLine("Usage: ApiFingerprintGen <inspect|write|check> <SDK.dll> --references <reference-directory> [--output <generated.cs>] [--canonical <canonical.json>]");
    return 2;
}
try
{
    var assemblyPath = Path.GetFullPath(args[1]);
    var referenceDirectory = Path.GetFullPath(args[3]);
    MetadataLimits.Validate(assemblyPath, referenceDirectory);
    string? output = null, canonicalFile = null;
    for (int i = 4; i < args.Length; i += 2)
        if (args[i] == "--output") output = Path.GetFullPath(args[i + 1]);
        else if (args[i] == "--canonical") canonicalFile = Path.GetFullPath(args[i + 1]);
        else throw new ArgumentException("Unknown option: " + args[i]);
    var references = Directory.EnumerateFiles(referenceDirectory, "*.dll").OrderBy(x => x, StringComparer.Ordinal)
        .Select(path => (MetadataReference)MetadataReference.CreateFromFile(path)).ToList();
    var sdkReference = MetadataReference.CreateFromFile(assemblyPath);
    references.Add(sdkReference);
    var compilation = CSharpCompilation.Create("ApiFingerprintMetadata", references: references,
        options: new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary, metadataImportOptions: MetadataImportOptions.All));
    var assembly = compilation.GetAssemblyOrModuleSymbol(sdkReference) as IAssemblySymbol
        ?? throw new InvalidDataException("SDK input does not contain an assembly.");
    var canonical = new CanonicalApi(assembly, assemblyPath, compilation).Read();
    var fingerprint = Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(canonical))).ToLowerInvariant();
    if (canonicalFile != null) File.WriteAllText(canonicalFile, canonical, new UTF8Encoding(false));
    var generated = "// Generated by ApiFingerprintGen from the compiled public SDK signatures.\n"
        + "namespace ForgeEngine.Framework;\n\npublic static class RuntimeApi\n{\n"
        + "    public const string Fingerprint = \"" + fingerprint + "\";\n}\n";
    if (args[0] == "write")
    {
        if (output == null) throw new ArgumentException("write requires --output.");
        File.WriteAllText(output, generated, new UTF8Encoding(false));
    }
    if (args[0] == "check")
    {
        var field = assembly.GetTypeByMetadataName("ForgeEngine.Framework.RuntimeApi")?.GetMembers("Fingerprint").OfType<IFieldSymbol>().SingleOrDefault();
        if (field?.ConstantValue as string != fingerprint) throw new InvalidDataException("api-fingerprint-stale: compiled SDK fingerprint does not match its public signatures. Regenerate and rebuild.");
        if (output != null && (!File.Exists(output) || File.ReadAllText(output).Replace("\r\n", "\n", StringComparison.Ordinal) != generated)) throw new InvalidDataException("api-fingerprint-stale: generated source differs from the compiled public signatures.");
    }
    Console.WriteLine(fingerprint);
    return 0;
}
catch (Exception error)
{
    Console.Error.WriteLine("ApiFingerprintGen: " + error.Message);
    return 1;
}
