"""Validate and build a deterministic ForgeAudio Thunderstore ZIP; never publishes.

Run after a Release build, from any directory:
    python Mods/ForgeAudio/tools/package_release.py --artifacts-path artifacts/dotnet-fix-akimpl
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import struct
import subprocess
import sys
import tempfile
from urllib.parse import urlsplit
import xml.etree.ElementTree as ElementTree
import zipfile


REPO = Path(__file__).resolve().parents[3]
PACKAGE = REPO / "Mods" / "ForgeAudio"
# web-manifest.json is the capability manifest the website reads (generated by Mods/Release/export-library-manifests).
METADATA = ("manifest.json", "icon.png", "README.md", "DEVELOPERS.md", "CHANGELOG.md", "LICENSE", "web-manifest.json")
NAME = r"[A-Za-z0-9_]{1,128}"
VERSION = r"(?:0|[1-9][0-9]*)\.(?:0|[1-9][0-9]*)\.(?:0|[1-9][0-9]*)"
BEPINEX_DEPENDENCY = "BepInEx-BepInExPack_GTFO-3.2.4"
FORGE_CORE_DEPENDENCY = re.compile(r"NAinfini-ForgeCore-\d+\.\d+\.\d+")


def check_package(folder: Path) -> dict[str, object]:
    try:
        manifest = json.loads((folder / "manifest.json").read_text(encoding="utf-8"))
    except FileNotFoundError as error:
        raise ValueError("manifest.json is missing") from error
    if not isinstance(manifest, dict):
        raise ValueError("manifest.json must be an object")
    for key in ("name", "version_number", "website_url", "description"):
        if not isinstance(manifest.get(key), str):
            raise ValueError(key + " must be a string")
    if not re.fullmatch(NAME, manifest["name"]):
        raise ValueError("name must be 1-128 letters, digits or underscores")
    if not re.fullmatch(VERSION, manifest["version_number"]):
        raise ValueError("version_number must be major.minor.patch")
    if len(manifest["description"]) > 250:
        raise ValueError("description exceeds 250 characters")
    url = urlsplit(manifest["website_url"])
    if manifest["website_url"] and (url.scheme not in ("http", "https") or not url.netloc):
        raise ValueError("website_url must be empty or an HTTP(S) URL")
    dependencies = manifest.get("dependencies")
    if not isinstance(dependencies, list) or any(
        not isinstance(dependency, str) or not re.fullmatch(NAME + "-" + NAME + "-" + VERSION, dependency)
        for dependency in dependencies
    ):
        raise ValueError("dependencies must be a list of Team-Name-major.minor.patch strings")
    if manifest["name"] != "ForgeAudio" or not (len(dependencies) == 2 and dependencies[0] == BEPINEX_DEPENDENCY and FORGE_CORE_DEPENDENCY.fullmatch(dependencies[1])):
        raise ValueError("expected ForgeAudio with only BepInEx and ForgeCore (NAinfini-ForgeCore-<version>)")

    icon_path = folder / "icon.png"
    if not icon_path.is_file():
        raise ValueError("icon.png is missing; provide a dedicated 256 x 256 ForgeAudio icon")
    with icon_path.open("rb") as icon:
        head = icon.read(33)
    if len(head) != 33 or head[:16] != b"\x89PNG\r\n\x1a\n\x00\x00\x00\x0dIHDR" or struct.unpack(">II", head[16:24]) != (256, 256):
        raise ValueError("icon.png must be a 256 x 256 PNG")
    for name in ("README.md", "DEVELOPERS.md", "CHANGELOG.md"):
        try:
            if not (folder / name).read_text(encoding="utf-8").strip():
                raise ValueError(name + " must not be empty")
        except FileNotFoundError as error:
            raise ValueError(name + " is missing") from error
    return manifest


def project_version(project: Path) -> str:
    try:
        root = ElementTree.parse(project).getroot()
    except (OSError, ElementTree.ParseError) as error:
        raise ValueError("cannot read " + project.name + ": " + str(error)) from error
    versions = [node.text.strip() for node in root.iter("Version") if node.text and node.text.strip()]
    if len(set(versions)) != 1:
        raise ValueError(project.name + " must contain one unambiguous Version")
    return versions[0]


def assembly_version(dll: Path) -> str:
    if not dll.is_file():
        raise ValueError("missing " + str(dll))
    if not dll.read_bytes()[:2] == b"MZ":
        raise ValueError("ForgeAudio.dll is not a PE assembly")
    powershell = shutil.which("pwsh") or shutil.which("powershell")
    if not powershell:
        raise ValueError("PowerShell is required to read the DLL assembly version")
    command = [
        powershell,
        "-NoProfile",
        "-NonInteractive",
        "-Command",
        "& { param([string]$p) [System.Reflection.AssemblyName]::GetAssemblyName($p).Version.ToString() }",
        str(dll),
    ]
    result = subprocess.run(command, capture_output=True, text=True, encoding="utf-8", errors="replace", check=False)
    if result.returncode:
        raise ValueError("cannot read ForgeAudio.dll assembly version: " + (result.stderr or result.stdout).strip())
    value = result.stdout.strip()
    if not re.fullmatch(r"\d+\.\d+\.\d+\.\d+", value):
        raise ValueError("ForgeAudio.dll has invalid assembly version " + repr(value))
    major, minor, patch, revision = value.split(".")
    if revision != "0":
        raise ValueError("ForgeAudio.dll assembly revision must be 0, found " + revision)
    return ".".join((major, minor, patch))


def package(folder: Path, dll: Path, output: Path) -> Path:
    manifest = check_package(folder)
    version = str(manifest["version_number"])
    declared = project_version(folder / "ForgeAudio.csproj")
    built = assembly_version(dll)
    if version != declared or version != built:
        raise ValueError("version mismatch: manifest " + version + ", project " + declared + ", DLL " + built)

    files = {name: (folder / name).read_bytes() for name in METADATA}
    files["ForgeAudio.dll"] = dll.read_bytes()
    decoder = dll.parent / "NVorbis.dll"
    files["NVorbis.dll"] = decoder.read_bytes()
    files["NVorbis.LICENSE"] = (folder / "vendor" / "NVorbis" / "LICENSE").read_bytes()
    files["NVorbis.NOTICE.md"] = (folder / "vendor" / "NVorbis" / "NOTICE.md").read_bytes()
    output.mkdir(parents=True, exist_ok=True)
    path = output / ("NAinfini-ForgeAudio-" + version + ".zip")
    file_handle, temporary_name = tempfile.mkstemp(prefix=path.name + ".", suffix=".tmp", dir=output)
    os.close(file_handle)
    temporary = Path(temporary_name)
    try:
        with zipfile.ZipFile(temporary, "w", compression=zipfile.ZIP_DEFLATED) as archive:
            for name, data in sorted(files.items()):
                info = zipfile.ZipInfo(name, date_time=(2026, 1, 1, 0, 0, 0))
                info.create_system = 3
                info.compress_type = zipfile.ZIP_DEFLATED
                info.external_attr = 0o644 << 16
                archive.writestr(info, data, compresslevel=9)
        os.replace(temporary, path)
    finally:
        temporary.unlink(missing_ok=True)
    print(path.name + ": " + str(path.stat().st_size) + " bytes, sha256 " + hashlib.sha256(path.read_bytes()).hexdigest())
    return path


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--artifacts-path", type=Path, default=Path("artifacts/dotnet-audiokit"))
    parser.add_argument("--output", type=Path, default=Path("artifacts/work/release-packages"))
    args = parser.parse_args()
    artifacts = args.artifacts_path if args.artifacts_path.is_absolute() else REPO / args.artifacts_path
    output = args.output if args.output.is_absolute() else REPO / args.output
    dll = artifacts / "bin" / "ForgeAudio" / "release" / "ForgeAudio.dll"
    try:
        package(PACKAGE, dll, output)
        return 0
    except (OSError, ValueError) as error:
        print("package_release: " + str(error), file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
