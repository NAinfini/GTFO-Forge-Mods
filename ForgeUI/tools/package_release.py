"""Validate and build a deterministic ForgeUI Thunderstore ZIP; never publishes.

Rules: https://wiki.thunderstore.io/mods/creating-a-package
Run after a Release build, from any directory:
    python Mods/ForgeUI/tools/package_release.py --artifacts-path artifacts/dotnet-fix-fix-perf-uikit
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import struct
import sys
from urllib.parse import urlsplit
import zipfile

REPO = Path(__file__).resolve().parents[3]
PACKAGE = REPO / "Mods/ForgeUI"
# web-manifest.json is the capability manifest the website reads (generated by Mods/Release/export-library-manifests).
METADATA = ("manifest.json", "icon.png", "README.md", "CHANGELOG.md", "LICENSE", "web-manifest.json")
NAME = r"[A-Za-z0-9_]{1,128}"
VERSION = r"(?:0|[1-9][0-9]*)\.(?:0|[1-9][0-9]*)\.(?:0|[1-9][0-9]*)"
BEPINEX_DEPENDENCY = "BepInEx-BepInExPack_GTFO-3.2.4"
FORGE_CORE_DEPENDENCY = re.compile(r"NAinfini-ForgeCore-\d+\.\d+\.\d+")
FONTS = ("ForgeUI-fonts.bundle", "OFL-Rajdhani.txt", "OFL-GlowSans.txt")


def check_package(folder):
    manifest = json.loads((folder / "manifest.json").read_text(encoding="utf-8"))
    if not isinstance(manifest, dict):
        raise ValueError("manifest.json must be an object")
    for key in ("name", "version_number", "website_url", "description"):
        if not isinstance(manifest.get(key), str):
            raise ValueError(key + " must be a string")
    if not re.fullmatch(NAME, manifest["name"]):
        raise ValueError("name must be 1-128 letters, digits or underscores")
    if not re.fullmatch(VERSION, manifest["version_number"]):
        raise ValueError("version_number must be major.minor.patch")
    if len(manifest["description"]) > 250:
        raise ValueError("description exceeds 250 characters")
    url = urlsplit(manifest["website_url"])
    if manifest["website_url"] and (url.scheme not in ("http", "https") or not url.netloc):
        raise ValueError("website_url must be empty or an HTTP(S) URL")
    deps = manifest.get("dependencies")
    if not isinstance(deps, list) or any(not isinstance(d, str) or not re.fullmatch(NAME + "-" + NAME + "-" + VERSION, d) for d in deps):
        raise ValueError("dependencies must be a list of Team-Name-major.minor.patch strings")
    if manifest["name"] != "ForgeUI" or not (len(deps) == 2 and deps[0] == BEPINEX_DEPENDENCY and FORGE_CORE_DEPENDENCY.fullmatch(deps[1])):
        raise ValueError("expected ForgeUI with only BepInEx and ForgeCore (NAinfini-ForgeCore-<version>)")
    with (folder / "icon.png").open("rb") as icon:
        head = icon.read(33)
    if len(head) != 33 or head[:16] != b"\x89PNG\r\n\x1a\n\x00\x00\x00\x0dIHDR" or struct.unpack(">II", head[16:24]) != (256, 256):
        raise ValueError("icon.png must be a 256 x 256 PNG")
    for name in ("README.md", "CHANGELOG.md"):
        if not (folder / name).read_text(encoding="utf-8").strip():
            raise ValueError(name + " must not be empty")
    return manifest


def package(folder, dll, output):
    manifest = check_package(folder)
    # Read every input before creating an output, so missing files cannot leave a partial package.
    files = {name: (folder / name).read_bytes() for name in METADATA}
    languages = sorted((folder / "lang").glob("*.json"))
    if not {"en.json", "zh.json"} <= {path.name for path in languages}:
        raise ValueError("lang/ must hold en.json and zh.json")
    for path in languages:
        if not isinstance(json.loads(path.read_text(encoding="utf-8")), dict):
            raise ValueError("lang/" + path.name + " must be a JSON object of key -> text")
        files["lang/" + path.name] = path.read_bytes()
    # The kit's fonts (tools/fonts/build_fonts.ps1) and their licences.
    for name in FONTS:
        path = folder / "Assets/fonts" / name
        if not path.is_file():
            raise ValueError("Assets/fonts/" + name + " is missing; run tools/fonts/build_fonts.ps1")
        files["fonts/" + name] = path.read_bytes()
    if not files["fonts/ForgeUI-fonts.bundle"].startswith(b"UnityFS"):
        raise ValueError("ForgeUI-fonts.bundle is not a Unity bundle")
    files["ForgeUI.dll"] = dll.read_bytes()
    if not files["ForgeUI.dll"].startswith(b"MZ"):
        raise ValueError("ForgeUI.dll is not a PE assembly")
    output.mkdir(parents=True, exist_ok=True)
    path = output / ("NAinfini-" + manifest["name"] + "-" + manifest["version_number"] + ".zip")
    with zipfile.ZipFile(path, "w", compression=zipfile.ZIP_DEFLATED) as archive:
        for name, data in sorted(files.items()):
            info = zipfile.ZipInfo(name, date_time=(2026, 1, 1, 0, 0, 0))
            info.create_system = 3
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            archive.writestr(info, data, compresslevel=9)
    print(path.name + ": " + str(path.stat().st_size) + " bytes, sha256 " + hashlib.sha256(path.read_bytes()).hexdigest())
    return path


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--artifacts-path", type=Path, default=Path("artifacts/dotnet-uikit"))
    args = parser.parse_args()
    dll = REPO / args.artifacts_path / "bin/ForgeUI/release/ForgeUI.dll"
    try:
        package(PACKAGE, dll, REPO / "artifacts/work/release-packages")
    except (OSError, ValueError) as error:
        sys.exit("package_release: " + str(error))


if __name__ == "__main__":
    main()
